export function translateText(value: string, locale: Locale): string {
  if (locale === 'zh-CN' || !/[\u3400-\u9fff]/u.test(value)) return value

  const leadingWhitespace = value.match(/^\s*/u)?.[0] ?? ''
  const trailingWhitespace = value.match(/\s*$/u)?.[0] ?? ''
  const normalized = value.trim().replace(/\s+/gu, ' ')
  const exact = englishMessages[normalized]
  if (exact !== undefined) return `${leadingWhitespace}${exact}${trailingWhitespace}`

  for (const [pattern, render] of dynamicMessages) {
    const match = normalized.match(pattern)
    if (match) return `${leadingWhitespace}${render(...match.slice(1))}${trailingWhitespace}`
  }

  return value
}
